#!/usr/bin/env node
// 16.9: declarations for the deprecated motionary/scene/v3-preview entry (= components/scene-v3-preview). Its JavaScript
// forwards to motionary/scene/v3 with the same API, so its types are a re-export of scene-v3 instead of a second bundled
// copy of the Scene v3 types (~10 KB per file; keeps the npm tarball under its fixed 14 MB limit). Runs after the build
// (package.json "build"); does nothing once the entry is gone (17.0).
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HEAD = "// motionary/scene/v3-preview — deprecated in 16.9, removed in 17.0 (generated by scripts/alias-dts.mjs).\n// Same API as motionary/scene/v3: import from 'motionary/scene/v3' (npx motionary migrate --to 17 --write).\n/** @deprecated Import from 'motionary/scene/v3' — this path is removed in 17.0 (docs/deprecations-v17.md#scene-v3-preview). */\n";

/** Writes the two declaration files; returns how many were written (0 when the entry does not exist). */
export function run(dist = fileURLToPath(new URL('../dist/', import.meta.url))) {
  const c = join(dist, 'components');
  if (!existsSync(join(c, 'scene-v3-preview.js'))) return 0;
  writeFileSync(join(c, 'scene-v3-preview.d.ts'), HEAD + "export * from './scene-v3.js';\n");
  writeFileSync(join(c, 'scene-v3-preview.d.cts'), HEAD + "export * from './scene-v3.cjs';\n");
  return 2;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) console.log(`alias dts: ${run()} file(s)`);
