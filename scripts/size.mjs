// Print raw / gzipped sizes of the build outputs and of tree-shaken imports,
// and with `--check` fail when an entry exceeds its gzip budget in
// size-budget.json. Run after `npm run build`.
// 16.3: `--report` writes docs/size-report.json (gzip bytes per budget entry, measured on this build) — the README
// size tables are generated from it (scripts/readme-sync.mjs). `--check` also fails when a README-table entry measured
// now differs from the committed report by more than 64 bytes gzip (the tables would be stale).
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { rollup } from 'rollup';
import terser from '@rollup/plugin-terser';

const check = process.argv.includes('--check');
const report = process.argv.includes('--report');
const budgets = JSON.parse(readFileSync(new URL('../size-budget.json', import.meta.url), 'utf8'));
const gz = (code) => gzipSync(code, { level: 9 }).length;
// Resolve `pkg` / `pkg/<sub>` through package.json `exports` (as a consumer would), so a budget on a removed or
// unexported path fails instead of silently measuring the dist file behind it.
const exportsMap = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).exports;
const resolvePkg = (id) => {
  const key = id === 'pkg' ? '.' : './' + id.slice(4);
  const e = exportsMap[key];
  const file = e && (typeof e === 'string' ? e : e.import?.default ?? e.default);
  if (!file) throw new Error(`size budget imports '${id.replace(/^pkg/, 'motionary')}', which package.json does not export`);
  return file.replace(/^\.\//, '');
};
const rows = [];
const fmt = (n) => (n / 1024).toFixed(2) + ' kB';

// `static: true` (15.0+): sum the entry chunk and every chunk it imports statically
// (lazy `import()` chunks excluded); `inline: true`: one bundle incl. lazy chunks.
async function treeShaken(source, opts = {}) {
  const bundle = await rollup({
    input: 'entry',
    onwarn: () => undefined,
    external: ['solid-js'],
    plugins: [
      {
        name: 'virtual',
        resolveId: (id) => (id === 'entry' ? id : id === 'pkg' || id.startsWith('pkg/') ? resolvePkg(id) : null),
        load: (id) => (id === 'entry' ? source : null),
      },
      terser(),
    ],
  });
  const { output } = await bundle.generate({ format: 'es', inlineDynamicImports: !!opts.inline });
  if (!opts.static) return Buffer.from(output[0].code);
  const byName = new Map(output.map((o) => [o.fileName, o]));
  const seen = new Set();
  const walk = (f) => { if (seen.has(f)) return; seen.add(f); for (const i of byName.get(f).imports ?? []) walk(i); };
  walk(output[0].fileName);
  return Buffer.concat([...seen].map((f) => Buffer.from(byName.get(f).code)));
}

for (const b of budgets) {
  let code;
  if (b.file) {
    if (!existsSync(b.file)) {
      rows.push({ ...b, missing: true });
      continue;
    }
    code = readFileSync(b.file);
  } else {
    code = await treeShaken(b.import, b);
  }
  rows.push({ ...b, raw: code.length, gz: gz(code) });
}

let failed = false;
console.log('| Entry | Size | Gzip | Budget (gzip) | |');
console.log('|---|---:|---:|---:|---|');
for (const r of rows) {
  if (r.missing) {
    console.log(`| ${r.name} | – | – | ${fmt(r.limit)} | ❌ missing |`);
    failed = true;
    continue;
  }
  const ok = r.gz <= r.limit;
  if (!ok) failed = true;
  console.log(`| ${r.name} | ${fmt(r.raw)} | ${fmt(r.gz)} | ${fmt(r.limit)} | ${ok ? '✅' : '❌ over budget'} |`);
}
if (check && failed) {
  console.error('\nSize budget exceeded (see size-budget.json).');
  process.exit(1);
}

const REPORT = new URL('../docs/size-report.json', import.meta.url);
if (report) {
  const version = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
  const out = { note: 'Generated by `npm run build && node scripts/size.mjs --report` — do not edit. gzip bytes [measured, budget].', version, rows: {} };
  for (const r of rows) if (!r.missing) out.rows[r.name] = [r.gz, r.limit];
  writeFileSync(REPORT, JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"') + '\n');
  console.log(`\nsize report written: docs/size-report.json (${Object.keys(out.rows).length} entries, ${version})`);
}
if (check && existsSync(REPORT)) {
  const { README_ROWS } = await import('./readme-sync.mjs');
  const committed = JSON.parse(readFileSync(REPORT, 'utf8')).rows;
  const drift = [];
  for (const [, name] of README_ROWS) {
    const now = rows.find((r) => r.name === name);
    if (!now || now.missing || !committed[name] || Math.abs(now.gz - committed[name][0]) > 64) drift.push(`${name}: report ${committed[name]?.[0]} B, measured ${now?.gz} B`);
  }
  if (drift.length) {
    console.error(`\nREADME size table stale (docs/size-report.json) — run: npm run build && node scripts/size.mjs --report && node scripts/readme-sync.mjs\n  ${drift.join('\n  ')}`);
    process.exit(1);
  }
  console.log('README size table matches this build (±64 B gzip)');
}
