// 12.3: writes figma-plugin/code.js from figma-plugin/plugin-src.js — embeds the component catalog (tag → bundle, runtime modules,
// attributes, official peers; from the AI manifest), the default motion tokens and the CDN major. `--check` exits 1 when stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { buildManifest } from './gen-manifest.mjs';

const HERE = (() => { try { return fileURLToPath(new URL('..', import.meta.url)); } catch { return ''; } })(); // tests import this under jsdom (non-file URL)
const ROOT = HERE && existsSync(join(HERE, 'package.json')) ? HERE : process.cwd();
const read = (f) => readFileSync(join(ROOT, f), 'utf8');

export function generate() {
  const m = buildManifest();
  const peers = new Set((m.runtimeModules || []).filter((v) => v.kind === 'peer').map((v) => v.id));
  const catalog = {};
  for (const c of [...m.components].sort((a, b) => a.tag.localeCompare(b.tag))) {
    const r = (c.requires || []).filter((x) => !x.startsWith('@') && !peers.has(x));
    const p = (c.requires || []).filter((x) => x.startsWith('@') || peers.has(x));
    // 13.2: b = 'w' widgets.umd.js, 'c' components.umd.js, 'm' own ES module entry (m = dist path, d = define function)
    const mod = !/\.umd\.js$/.test(c.cdn || '') && (c.cdn || '').match(/\/dist\/(.+)$/);
    catalog[c.tag] = { b: mod ? 'm' : /widgets\.umd\.js$/.test(c.cdn || '') ? 'w' : 'c', ...(mod ? { m: mod[1], d: c.import.define } : {}), r, a: c.attributes || [], ...(p.length ? { p } : {}) };
  }
  const major = String(m.version).split('.')[0];
  const tokens = JSON.parse(read('docs/motion.tokens.json'));
  const keep = { motion: { duration: tokens.motion.duration, easing: tokens.motion.easing } };
  const src = read('figma-plugin/plugin-src.js')
    .replace("'/*MAJOR*/'", JSON.stringify(major))
    .replace('/*CATALOG*/ {}', JSON.stringify(catalog))
    .replace('/*TOKENS*/ {}', JSON.stringify(keep));
  return { 'figma-plugin/code.js': '// GENERATED by scripts/gen-figma-plugin.mjs from figma-plugin/plugin-src.js — do not edit.\n' + src };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [f, s] of Object.entries(generate())) {
    const p = join(ROOT, f), cur = existsSync(p) ? readFileSync(p, 'utf8') : null;
    if (cur === s) continue;
    if (check) stale.push(f); else writeFileSync(p, s);
  }
  if (stale.length) { console.error(`❌ ${stale.join(', ')} out of date — run node scripts/gen-figma-plugin.mjs`); process.exit(1); }
  console.log(check ? 'figma plugin up to date' : 'figma plugin written');
}
