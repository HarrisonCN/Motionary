// 11.5: type declarations for the deprecated subpaths (bin/public-paths.mjs DEPRECATED_PATHS).
// The old path keeps its JavaScript (the same dist file as the new path); only its `types` point here, where every
// export is re-exported with a `@deprecated` tag naming the replacement. Editors strike the import through; nothing runs.
// Runs after the build (package.json "build"), writes dist/deprecated/<old-path>.d.ts and .d.cts.
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { DEPRECATED_PATHS, REMOVED_IN } from '../bin/public-paths.mjs';

/** File name under dist/deprecated/ for an old subpath (`components/ai` → `components-ai`). */
export const deprecatedFile = (oldPath) => oldPath.replace(/\//g, '-');

/** The declaration text: `export { /** @deprecated … *\/ a, … } from '<target>'`. */
export function deprecatedDts(oldPath, newPath, target, names) {
  const msg = `Import from 'motionary/${newPath}' instead — 'motionary/${oldPath}' is deprecated since 11.5 and removed in ${REMOVED_IN} (npx motionary doctor · npx usa-codemod-13 --write).`;
  const lines = names.map(({ name, type }) => `  /** @deprecated ${msg} */ ${type ? 'type ' : ''}${name},`);
  return `// motionary/${oldPath} — deprecated alias of motionary/${newPath} (generated by scripts/gen-deprecated-types.mjs)\nexport {\n${lines.join('\n')}\n} from '${target}';\n`;
}

/** Exported names of a bundled declaration file, with whether each is type-only. */
export function exportsOf(dtsFile) {
  const require = createRequire(import.meta.url);
  const ts = require('typescript');
  const program = ts.createProgram([dtsFile], { noEmit: true, skipLibCheck: true, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext });
  const checker = program.getTypeChecker();
  const sf = program.getSourceFile(dtsFile);
  const sym = checker.getSymbolAtLocation(sf);
  return checker.getExportsOfModule(sym).map((s) => {
    const r = s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s;
    return { name: s.getName(), type: !(r.flags & ts.SymbolFlags.Value) };
  }).sort((a, b) => a.name.localeCompare(b.name));
}

export function run(dist = new URL('../dist/', import.meta.url)) {
  mkdirSync(new URL('deprecated/', dist), { recursive: true });
  let n = 0;
  for (const [oldPath, newPath] of Object.entries(DEPRECATED_PATHS)) {
    if (oldPath.endsWith('.json')) continue;
    // the dist file both paths serve: components/<x> (motionary/design and motionary/core live there too)
    const base = oldPath.startsWith('components/') ? oldPath : `components/${oldPath}`;
    const file = new URL(`${base}.d.ts`, dist);
    if (!existsSync(file)) throw new Error(`gen-deprecated-types: missing ${file.pathname}`);
    const names = exportsOf(file.pathname);
    for (const [ext, js] of [['d.ts', 'js'], ['d.cts', 'cjs']])
      writeFileSync(new URL(`deprecated/${deprecatedFile(oldPath)}.${ext}`, dist), deprecatedDts(oldPath, newPath, `../${base}.${js}`, names));
    n++;
  }
  console.log(`deprecated types: ${n} old subpaths → dist/deprecated/`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) run();
