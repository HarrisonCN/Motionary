#!/usr/bin/env node
// 13.5.0: framework element types generated from the component manifest (dist/manifest.json).
//   node scripts/gen-framework-types.mjs           → writes src/components/frameworks/elements.generated.ts
//   node scripts/gen-framework-types.mjs --check   → exits 1 when the committed file is stale (CI: check:docs)
// One interface per concern, keyed by tag: the attributes each element documents and the events it dispatches.
// motionary/components/jsx (React 19 / Solid JSX), …/vue (GlobalComponents), …/svelte (svelte/elements) and
// motionary/angular (HTMLElementTagNameMap + event names) build their framework-specific types from these maps.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/components/frameworks/elements.generated.ts');
const manifestPath = join(ROOT, 'dist/manifest.json');
if (!existsSync(manifestPath)) {
  console.error('gen-framework-types: dist/manifest.json missing — run `npm run build` first');
  process.exit(2);
}
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const ident = /^[A-Za-z_$][\w$]*$/;
const key = (s) => (ident.test(s) ? s : q(s));

const comps = [...manifest.components].filter((c) => /^usa-[a-z0-9-]+$/.test(c.tag)).sort((a, b) => a.tag.localeCompare(b.tag));
const seen = new Set();
const rows = comps.filter((c) => !seen.has(c.tag) && seen.add(c.tag));

let attrs = '';
let events = '';
for (const c of rows) {
  const doc = `  /** \`<${c.tag}>\` — ${String(c.title || c.id).replace(/\*\//g, '*\\/')} (${c.import?.path || c.entry || 'motionary'}). */\n`;
  const a = [...new Set(c.attributes || [])].filter((x) => /^[a-z][a-z0-9-]*$/.test(x)).sort();
  attrs += doc + `  ${q(c.tag)}: {${a.length ? ' ' + a.map((x) => `${key(x)}?: string | boolean | number`).join('; ') + ' ' : ''}};\n`;
  const e = [...new Set(c.events || [])].filter((x) => /^[a-z][a-z0-9:-]*$/.test(x)).sort();
  events += `  ${q(c.tag)}: {${e.length ? ' ' + e.map((x) => `${q(x)}: CustomEvent<any>`).join('; ') + ' ' : ''}};\n`;
}

const src = `// GENERATED by scripts/gen-framework-types.mjs from dist/manifest.json (${rows.length} elements) — do not edit by hand.
// Regenerate: \`npm run gen:framework-types\` (checked in CI by \`npm run check:docs\`).
/* eslint-disable */

/** Documented attributes of every shipped \`<usa-*>\` element, keyed by tag (attribute values are strings / flags). */
export interface UsaElementAttributeMap {
${attrs}}

/** The \`usa:*\` events each element dispatches, keyed by tag (\`detail\` shape: see the element's docs). */
export interface UsaElementEventMap {
${events}}

/** Every shipped \`<usa-*>\` tag. */
export type UsaElementTag = keyof UsaElementAttributeMap;
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== src) {
    console.error('gen-framework-types: src/components/frameworks/elements.generated.ts is stale — run `npm run gen:framework-types`');
    process.exit(1);
  }
  console.log(`gen-framework-types: up to date (${rows.length} elements)`);
} else {
  writeFileSync(OUT, src);
  console.log(`gen-framework-types: wrote ${rows.length} elements → src/components/frameworks/elements.generated.ts`);
}
