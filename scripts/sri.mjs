#!/usr/bin/env node
// 16.3: Subresource Integrity hashes for the no-build CDN files of THIS version, written into docs/cdn-sri.md between
// <!-- sri:start --> and <!-- sri:end -->. Run after `npm run build` on the release build (the release tooling runs
// it right before the dist commit, so the hashes are those of the files published to npm / served by unpkg + jsDelivr).
// `--check` exits 1 when the table does not match dist/ (local release check; CI rebuilds dist, so it is not in check:docs).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const HERE = (() => { try { return fileURLToPath(new URL('..', import.meta.url)); } catch { return ''; } })();
const ROOT = HERE && existsSync(join(HERE, 'package.json')) ? HERE : process.cwd();
const FILES = ['dist/index.umd.js', 'dist/presets-extended.umd.js', 'dist/components.umd.js', 'dist/components.css', 'dist/widgets.umd.js', 'dist/element.umd.js'];

export function sriTable() {
  const v = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;
  const rows = FILES.filter((f) => existsSync(join(ROOT, f))).map((f) => {
    const h = 'sha384-' + createHash('sha384').update(readFileSync(join(ROOT, f))).digest('base64');
    return { f, h, url: `https://cdn.jsdelivr.net/npm/motionary@${v}/${f}` };
  });
  const tag = (r) => r.f.endsWith('.css')
    ? `<link rel="stylesheet" href="${r.url}" integrity="${r.h}" crossorigin="anonymous">`
    : `<script src="${r.url}" integrity="${r.h}" crossorigin="anonymous"></script>`;
  return [
    `Hashes for **motionary@${v}** (generated by \`scripts/sri.mjs\` from the release build):`,
    '',
    '| File | integrity |',
    '|---|---|',
    ...rows.map((r) => `| \`${r.f}\` | \`${r.h}\` |`),
    '',
    '```html',
    ...rows.filter((r) => /index\.umd|components\.(umd|css)/.test(r.f)).map(tag),
    '```',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const f = join(ROOT, 'docs/cdn-sri.md');
  const s = readFileSync(f, 'utf8');
  const a = '<!-- sri:start -->', b = '<!-- sri:end -->';
  const i = s.indexOf(a), j = s.indexOf(b);
  if (i < 0 || j < i) { console.error('docs/cdn-sri.md: sri markers missing'); process.exit(1); }
  const out = s.slice(0, i + a.length) + '\n' + sriTable() + '\n' + s.slice(j);
  if (process.argv.includes('--check')) {
    if (out !== s) { console.error('❌ docs/cdn-sri.md does not match dist/ — run node scripts/sri.mjs after the build'); process.exit(1); }
    console.log('SRI table matches dist/');
  } else { writeFileSync(f, out); console.log('docs/cdn-sri.md written'); }
}
