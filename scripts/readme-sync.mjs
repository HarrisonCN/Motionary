#!/usr/bin/env node
// 16.3: version numbers and the size table in the READMEs are generated, never typed by hand.
//   • <!--ver:version-->16.3.0<!--/ver-->   package.json version (README*.md, docs/versions.md)
//   • <!--ver:major-->16<!--/ver-->         its major (the CDN pin the docs recommend)
//   • every https://unpkg.com/motionary@N/… and https://cdn.jsdelivr.net/npm/motionary@N/… (and use-scroll-animate) in
//     README*.md and docs/versions.md points at the current major
//   • <!-- size-table:start --> … <!-- size-table:end -->  rows from docs/size-report.json, which
//     `npm run build && node scripts/size.mjs --report` measures on the real build (size:check fails when the
//     committed report drifts from the build by > 64 B gzip on any of these rows)
// `node scripts/readme-sync.mjs` writes; `--check` exits 1 when anything is stale (CI: npm run check:docs).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const HERE = (() => { try { return fileURLToPath(new URL('..', import.meta.url)); } catch { return ''; } })();
const ROOT = HERE && existsSync(join(HERE, 'package.json')) ? HERE : process.cwd();
const read = (f) => readFileSync(join(ROOT, f), 'utf8');

/** [label key, size-budget.json name] — the rows the README size tables show. */
export const README_ROWS = [
  ['core', "import 'motionary/core' (zero-dep core, fixed 10 KB)"],
  ['default', 'import default instance'],
  ['everything', 'import everything (minified)'],
  ['umd', 'dist/index.umd.js (minified)'],
  ['parallax', 'import { parallax }'],
  ['extended', "import 'motionary/presets/extended'"],
  ['runtime', "import 'motionary/runtime' (runtime core, fixed 5.5 KB)"],
  ['reveal', "import 'motionary/components/reveal'"],
  ['lite', "import 'motionary/components/lite'"],
  ['components', "import 'motionary/components' (everything)"],
  ['componentsUmd', 'dist/components.umd.js (minified, all components + CSS)'],
];

const LABELS = {
  en: { head: ['What you import', 'gzip', 'Budget'], core: '`motionary/core` (`createMotion`)', default: "`import ScrollAnimate from 'motionary'` (default instance)", everything: 'Everything from `motionary`', umd: '`dist/index.umd.js` (CDN)', parallax: '`parallax()` alone', extended: '`motionary/presets/extended` (181 presets)', runtime: '`motionary/runtime` (runtime core)', reveal: '`motionary/components/reveal`', lite: '`motionary/components/lite` (every element, CSS on demand)', components: '`motionary/components` (every element + CSS)', componentsUmd: '`dist/components.umd.js` (CDN, everything)', note: (v) => `Measured on the ${v} build (minified + gzip), generated by \`scripts/size.mjs --report\`:` },
  zh: { head: ['导入内容', 'gzip', '上限'], core: '`motionary/core`（`createMotion`）', default: "`import ScrollAnimate from 'motionary'`（默认实例）", everything: '`motionary` 全部导出', umd: '`dist/index.umd.js`（CDN）', parallax: '仅 `parallax()`', extended: '`motionary/presets/extended`（181 个预设）', runtime: '`motionary/runtime`（运行时核心）', reveal: '`motionary/components/reveal`', lite: '`motionary/components/lite`（全部元素，CSS 按需）', components: '`motionary/components`（全部元素 + CSS）', componentsUmd: '`dist/components.umd.js`（CDN，全部）', note: (v) => `${v} 构建的实测值（minify + gzip），由 \`scripts/size.mjs --report\` 生成：` },
  ja: { head: ['インポートするもの', 'gzip', '上限'], core: '`motionary/core`（`createMotion`）', default: "`import ScrollAnimate from 'motionary'`（デフォルトインスタンス）", everything: '`motionary` のすべて', umd: '`dist/index.umd.js`（CDN）', parallax: '`parallax()` のみ', extended: '`motionary/presets/extended`（181 プリセット）', runtime: '`motionary/runtime`（ランタイムのコア）', reveal: '`motionary/components/reveal`', lite: '`motionary/components/lite`（全要素、CSS はオンデマンド）', components: '`motionary/components`（全要素 ＋ CSS）', componentsUmd: '`dist/components.umd.js`（CDN、すべて）', note: (v) => `${v} ビルドでの実測値（minify ＋ gzip、\`scripts/size.mjs --report\` で生成）：` },
};

const kb = (b) => (b / 1024).toFixed(2) + ' KB';

export function sizeTable(report, lang) {
  const L = LABELS[lang];
  const rows = README_ROWS.map(([k, name]) => {
    const r = report.rows[name];
    if (!r) throw new Error(`docs/size-report.json has no row "${name}" — run node scripts/size.mjs --report after the build`);
    return `| ${L[k]} | ${kb(r[0])} | ${kb(r[1])} |`;
  });
  return [L.note(report.version), '', `| ${L.head.join(' | ')} |`, '|---|---:|---:|', ...rows].join('\n');
}

const CDN = /(https:\/\/(?:unpkg\.com|cdn\.jsdelivr\.net\/npm)\/(?:motionary|use-scroll-animate))@\d+(?=\/)/g;

export function generate() {
  const version = JSON.parse(read('package.json')).version;
  const major = version.split('.')[0];
  const report = existsSync(join(ROOT, 'docs/size-report.json')) ? JSON.parse(read('docs/size-report.json')) : null;
  const files = {};
  const ver = (s) => s
    .replace(/<!--ver:version-->[^<]*<!--\/ver-->/g, `<!--ver:version-->${version}<!--/ver-->`)
    .replace(/<!--ver:major-->[^<]*<!--\/ver-->/g, `<!--ver:major-->${major}<!--/ver-->`)
    .replace(CDN, `$1@${major}`);
  for (const [f, lang] of [['README.md', 'en'], ['README_zh.md', 'zh'], ['README_ja.md', 'ja']]) {
    let s = ver(read(f));
    const a = '<!-- size-table:start -->', b = '<!-- size-table:end -->';
    const i = s.indexOf(a), j = s.indexOf(b);
    if (i >= 0 && j > i) {
      if (!report) throw new Error('docs/size-report.json missing — run npm run build && node scripts/size.mjs --report');
      s = s.slice(0, i + a.length) + '\n' + sizeTable(report, lang) + '\n' + s.slice(j);
    }
    files[f] = s;
  }
  files['docs/versions.md'] = ver(read('docs/versions.md'));
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [f, s] of Object.entries(generate())) {
    if (read(f) === s) continue;
    if (check) stale.push(f); else writeFileSync(join(ROOT, f), s);
  }
  if (stale.length) { console.error(`❌ README versions / size table out of date: ${stale.join(', ')} — run node scripts/readme-sync.mjs`); process.exit(1); }
  console.log(check ? 'README versions and size tables up to date' : 'README versions and size tables written');
}
